-- Relational schema for the class intake CSV (one response per student).
-- Naming: snake_case tables and columns; singular table names.

CREATE TABLE tool (
    tool_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR NOT NULL UNIQUE
);

CREATE TABLE availability_slot (
    slot_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label         VARCHAR NOT NULL UNIQUE,
    day_type      VARCHAR NOT NULL,
    time_of_day   VARCHAR NOT NULL,
    CONSTRAINT availability_slot_day_type_check
        CHECK (day_type IN ('weekday', 'weekend')),
    CONSTRAINT availability_slot_time_of_day_check
        CHECK (time_of_day IN ('morning', 'afternoon', 'evening'))
);

CREATE TABLE student (
    student_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_identifier    VARCHAR NOT NULL UNIQUE,
    display_name         VARCHAR NOT NULL,
    school_year          VARCHAR NOT NULL,
    intro_programming    VARCHAR NOT NULL,
    skill_programming    SMALLINT NOT NULL,
    skill_data_stats     SMALLINT NOT NULL,
    skill_frontend_design SMALLINT NOT NULL,
    skill_business_pitch SMALLINT NOT NULL,
    working_style        TEXT,
    interests            TEXT NOT NULL,
    semester_goal        TEXT NOT NULL,
    submitted_at         TIMESTAMPTZ NOT NULL,
    CONSTRAINT student_school_year_check
        CHECK (school_year IN ('First-year', 'Sophomore', 'Junior', 'Senior')),
    CONSTRAINT student_intro_programming_check
        CHECK (intro_programming IN ('took_it', 'equivalent', 'neither')),
    CONSTRAINT student_skill_programming_check
        CHECK (skill_programming BETWEEN 1 AND 5),
    CONSTRAINT student_skill_data_stats_check
        CHECK (skill_data_stats BETWEEN 1 AND 5),
    CONSTRAINT student_skill_frontend_design_check
        CHECK (skill_frontend_design BETWEEN 1 AND 5),
    CONSTRAINT student_skill_business_pitch_check
        CHECK (skill_business_pitch BETWEEN 1 AND 5)
);

CREATE TABLE student_tool (
    student_id  INTEGER NOT NULL REFERENCES student (student_id),
    tool_id     INTEGER NOT NULL REFERENCES tool (tool_id),
    PRIMARY KEY (student_id, tool_id)
);

CREATE TABLE student_availability (
    student_id  INTEGER NOT NULL REFERENCES student (student_id),
    slot_id     INTEGER NOT NULL REFERENCES availability_slot (slot_id),
    PRIMARY KEY (student_id, slot_id)
);
